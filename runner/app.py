    skills_dir = KNOWLEDGE_BASE_ROOT / ".codex" / "skills"
    stale = any(
        p.stat().st_mtime > registry_mtime
        for p in skills_dir.rglob("skill.yaml")
        if p.exists()
    )
    if stale:
        logger.info("Registry stale — rebuilding from knowledge_base skills...")
        result = subprocess.run(
            [str(VENV_PYTHON if VENV_PYTHON.exists() else "python3"), str(_build_script), "--quiet", "--no-sync"],
            cwd=str(KNOWLEDGE_BASE_ROOT),
            capture_output=True, text=True,
        )
        if result.returncode == 0:
            logger.info("Registry rebuilt successfully.")
        else:
            logger.warning("Registry rebuild failed: %s", result.stderr.strip())

