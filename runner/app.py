    now = time.monotonic()
    for job in _running_jobs.values():
        try:
            started = datetime.fromisoformat(job["started_at"]).timestamp()
            total_s += time.time() - started
        except Exception:
            pass
    return jsonify({"total_s": round(total_s, 1)})










