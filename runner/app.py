def _ai_cli(agent: str) -> list[str]:
    """Return the CLI command prefix for the selected agent."""
    if agent == "codex":
        return ["codex", "exec", "--dangerously-bypass-approvals-and-sandbox", "--json"]
    if agent == "dsh":
        return dsh_cli.cli_prefix()
    # default: claude
    claude_bin = _PROTO / ".venv" / "bin" / "claude"
    bin_str = str(claude_bin) if claude_bin.exists() else "claude"
    return [bin_str, "-p", "--verbose", "--permission-mode", "bypassPermissions", *project_runs.CLAUDE_SETTINGS]


def _load_skill_md(skill_name: str | None, registry: dict[str, dict]) -> str:
    """Return the SKILL.md body for skill_name (frontmatter stripped), or empty string."""
    if not skill_name:
        return ""
    entry = registry.get(skill_name, {})
    skill_path = entry.get("skill_path")
    if not skill_path:
        return ""
    p = Path(skill_path)
    if not p.exists():
        return ""
    text = p.read_text(encoding="utf-8")
    # Strip YAML frontmatter (---...--- block at top)
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            text = text[end + 4:].lstrip("\n")
    return text.strip()


def _ai_command(
    agent: str,
    prompt: str,
    output_format: str = "json",
    skill_name: str | None = None,
    registry: dict[str, dict] | None = None,
    persist: bool = True,
) -> list[str]:
    """Build a non-interactive agent command with agent-specific flags.

    For Claude, the harness loads SKILL.md from ~/.claude/skills/ automatically.
    For Codex and DeepSeek, we prepend SKILL.md content to the prompt directly.
    persist=False (a one-off call such as skill routing) leaves no session in the agent's
    store, so it never shows up in `claude --resume` / `codex resume` (DP-28).
    """
    cli = _ai_cli(agent)
    if not persist and agent == "claude":
        cli = cli + ["--no-session-persistence"]
    elif not persist and agent == "codex":
        cli = cli[:2] + ["--ephemeral"] + cli[2:]  # an exec option: right after `codex exec`
    if agent == "claude":
        return cli + [prompt, "--output-format", output_format]
    # Codex / DeepSeek: inject skill instructions into prompt
    skill_content = _load_skill_md(skill_name, registry or {})
    if skill_content:
        full_prompt = f"## Skill Instructions\n\n{skill_content}\n\n## Task\n\n{prompt}"
    else:
        full_prompt = prompt
    if agent == "dsh":
        # Text mode prints only the final message; `--` keeps a leading "-" out of option parsing.
        return cli + ([] if output_format == "text" else ["--json"]) + ["--", full_prompt]
    return cli + [full_prompt]


