def _parse_run_footer(output: str) -> dict:
    """Scan last 20 lines of output for OUTPUT_PATH: and QUALITY: markers."""
    result: dict = {"output_path": "", "quality_score": None}
    for line in output.splitlines()[-20:]:
        s = line.strip()
        if s.startswith("OUTPUT_PATH:"):
            result["output_path"] = s[len("OUTPUT_PATH:"):].strip()
        elif s.startswith("QUALITY:"):
            try:
                result["quality_score"] = float(s[len("QUALITY:"):].strip())
            except ValueError:
                pass
    return result


def _compute_token_cost(
    output_tokens: int | None,
    input_tokens: int | None,
    model: str | None,
) -> float | None:
    """Estimate cost in USD using output-token pricing from MODEL_PRICES.

    Unknown model (dsh headless reports none) → None: no evidence for any price.
    """
    if not model or (not output_tokens and not input_tokens):
        return None
    # "claude-opus-5-5[1m]" -> "claude-opus-5-5". No prefix fallback: "gpt-5.4-mini" must not
    # silently price as "gpt-5.4" (STB-024/049).
    price_per_m = _MODEL_PRICES.get(re.sub(r"\[[^\]]*\]$", "", model), _DEFAULT_PRICE)
    total = (output_tokens or 0) + (input_tokens or 0)
    return round(total / 1_000_000 * price_per_m, 6)


def _write_run_log(skill: str, status: str, started_at: str, duration_s: float,
                   prompt: str = "", output: str = "", error: str = "",
                   run_id: str | None = None, output_path: str = "",
                   attempt: int = 0, parent_run_id: str | None = None,
                   linear_issue_id: str | None = None,
                   selected_skill: str | None = None,
                   input_tokens: int | None = None,
                   output_tokens: int | None = None,
                   agent: str | None = None,
                   model: str | None = None,
                   task_id: str | None = None,
                   quality_score: float | None = None,
                   token_cost_usd: float | None = None,
                   agent_session_id: str | None = None,
                   reset_generation: int | None = None,
                   extra: dict | None = None, audit: bool = False) -> str:
    # Every run-log writer (project runs, session cards, generic dispatch) comes through here, and
    # task state below reuses these strings: scrub the memory bearer token before either write.
    prompt = ai_memory.scrub_token(prompt)
    output = ai_memory.scrub_token(output)
    error = ai_memory.scrub_token(error)
    if extra:
        extra = ai_memory.scrub_record(extra)
    OUTPUTS_DIR.mkdir(parents=True, exist_ok=True)
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    if run_id is None:
        run_id = str(uuid.uuid4())
    if not audit:
        model = _OBSERVED_MODELS.pop(run_id, None) or model  # what the CLI said it ran (SBI-015)
    record: dict = {
        "run_id": run_id,
        "skill": skill,
        "status": status,
        "started_at": started_at,
        "duration_s": round(duration_s, 2),
        "prompt": prompt,
        "output": output,
        "error": error,
        "output_path": output_path,
        "attempt": attempt,
        "task_id": task_id or run_id,  # root task id; retry inherits from ancestor
    }
    if parent_run_id:
        record["parent_run_id"] = parent_run_id
    if linear_issue_id:
        record["linear_issue_id"] = linear_issue_id
    if selected_skill:
        record["selected_skill"] = selected_skill
    if input_tokens is not None:
        record["input_tokens"] = input_tokens
    if output_tokens is not None:
        record["output_tokens"] = output_tokens
    if agent:
        record["agent"] = agent
    if model:
        record["model"] = model
    if quality_score is not None:
        record["quality_score"] = quality_score
    if token_cost_usd is not None:
        record["token_cost_usd"] = token_cost_usd
    if agent_session_id:
        record["agent_session_id"] = agent_session_id
    if reset_generation is not None:
        record["reset_gen"] = reset_generation  # the generation this run launched under (Decision 11)
    if extra:
        record.update({k: v for k, v in extra.items() if k not in record})  # additive fields only
    if record.get("reply") and str(prompt).startswith("[withheld"):
        record["reply"] = ""  # the human turn is the prompt's text: withheld with it (AGE-114)
    limit_reset = None if audit else project_runs.LIMIT_RESETS.pop(run_id, None)
    # stopped by a usage limit (not by the user): continue its session once the limit resets (AGE-115)
    continue_at = max(limit_reset, time.time()) + AUTO_CONTINUE_GRACE_S if limit_reset and agent_session_id \
        and status in ("error", "review") else None
    if continue_at:
        record["auto_continue_at"] = datetime.fromtimestamp(continue_at, timezone.utc).isoformat()
    progress_path = _run_progress_path(run_id)
    if progress_path.exists():
        record["log_path"] = str(progress_path)

    record = _sanitize_record(record)
    # Write to both locations: state/ (operational truth) and outputs/ (backward compat)
    with STATE_RUN_LOG.open("a", encoding="utf-8") as f:
        f.write(json.dumps(record) + "\n")
    with RUN_LOG.open("a", encoding="utf-8") as f:
        f.write(json.dumps(record) + "\n")
    _runs_cache.clear()  # invalidate so next board refresh sees the new record
    if continue_at:
        _schedule_auto_continue(run_id, continue_at)
    _FINALIZING.discard(run_id)  # its record is on disk: shutdown need not wait for it (SBR-010)
    _RETIRING.pop(run_id, None)
    if audit:  # history only: no task/job state, it is not an execution (UI3-02)
        return run_id

    # Update task state in state/task_state.json (operational truth), one locked
    # read-modify-write so parallel completions never drop each other's record (4b).
    with file_lock(STATE_TASK_STATE):
        _update_task_state(skill, status, started_at, record, run_id, agent, model, input_tokens,
                           output_tokens, selected_skill, attempt, parent_run_id, linear_issue_id,
                           error, output, prompt, progress_path)

    with json_transaction(JOB_STATE, indent=2) as legacy_state:  # legacy job_state.json
        legacy_state[skill] = {"status": status, "last_run": started_at, "duration_s": record["duration_s"]}
    return run_id


AUTO_CONTINUE_GRACE_S = 120  # after the reported reset, so the continuation is not refused again
AUTO_CONTINUE_REPLY = "Your usage limit has reset. Continue the task from where you stopped."


def _auto_continue_path() -> Path:
    return STATE_DIR / "auto_continue.json"  # run_id -> epoch to continue at; survives a restart


def _schedule_auto_continue(run_id: str, at: float) -> None:
    """AGE-115: headless `claude -p` / `codex exec` exit when they hit a usage limit, so nothing is left waiting
    for the reset the way an interactive session does: the runner waits and continues it."""
    with json_transaction(_auto_continue_path()) as pending:
        pending[run_id] = at
    _arm_auto_continue(run_id, at)


def _arm_auto_continue(run_id: str, at: float) -> None:
    t = threading.Timer(max(0.0, at - time.time()), _auto_continue, (run_id,))
    t.daemon = True
    t.start()


def _rearm_auto_continues() -> None:
    for run_id, at in read_json(_auto_continue_path()).items():
        _arm_auto_continue(run_id, float(at))


def _auto_continue(run_id: str) -> None:
    """A quick reply (strict) to the stopped run, through the retry route: it is refused, and
    nothing runs, when the card was reset, removed or retried meanwhile, or its session is gone
    or held by an interactive terminal."""
    if _SHUTTING_DOWN.is_set():
        return  # the restarted runner re-arms it
    try:
        with app.test_client() as c:
            r = c.post(f"/api/runs/{run_id}/retry", json={"reply": AUTO_CONTINUE_REPLY, "strict": True},
                       headers={_TOKEN_HEADER: REQUEST_TOKEN})
        logger.info("[auto-continue] %s: %s %s", run_id, r.status_code,
                    (r.get_json(silent=True) or {}).get("error") or "started")
    except Exception:
        logger.exception("[auto-continue] %s failed", run_id)
    # ponytail: a refusal (e.g. maintenance) is not retried; the card shows the error, reply by hand
    with json_transaction(_auto_continue_path()) as pending:
        pending.pop(run_id, None)


def _update_task_state(skill, status, started_at, record, run_id, agent, model, input_tokens,
                       output_tokens, selected_skill, attempt, parent_run_id, linear_issue_id,
                       error, output, prompt, progress_path) -> None:
    """Append one run to task_state.json. Caller holds file_lock(STATE_TASK_STATE)."""
    state = _load_task_state()
    if skill not in state:
        state[skill] = {"runs": [], "status": "", "last_run": "", "duration_s": 0.0}
    # Append the new run record
    run_record = {
        "run_id": run_id,
        "skill": skill,
        "status": status,
        "started_at": started_at,
        "duration_s": record["duration_s"],
        "agent": agent,
        "model": model,
        "input_tokens": input_tokens,
        "output_tokens": output_tokens,
        "selected_skill": selected_skill or skill,
        "attempt": attempt,
        "parent_run_id": parent_run_id,
        "linear_issue_id": linear_issue_id,
        "error": error,
        "output": output,
        "prompt": prompt,
    }
    if progress_path.exists():
        run_record["log_path"] = str(progress_path)
    state[skill]["runs"].append(run_record)
    state[skill]["status"] = status
    state[skill]["last_run"] = started_at
    state[skill]["duration_s"] = record["duration_s"]
    write_json_atomic(STATE_TASK_STATE, state, indent=2)


