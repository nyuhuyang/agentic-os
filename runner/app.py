def _latest_linear_runs(include_archived: bool = True) -> dict[str, dict]:
    """Return newest local run record per Linear issue."""
    if not RUN_LOG.exists():
        return {}
    latest: dict[str, dict] = {}
    for line in reversed(RUN_LOG.read_text(encoding="utf-8").splitlines()):
        try:
            r = json.loads(line)
        except Exception:
            continue
        issue_id = r.get("linear_issue_id")
        if not issue_id or issue_id in latest:
            continue
        if not include_archived and r.get("status") == "archived":
            continue
        if not r.get("run_id"):
            h = hashlib.md5(f"{r.get('started_at','')}{r.get('skill','')}".encode()).hexdigest()[:8]
            r["run_id"] = f"legacy-{h}"
        latest[issue_id] = r
    return latest













def _extract_real_errors(stderr_s: str) -> str:
    """Filter verbose agent stderr (Codex session log) to only real error lines."""
    lines = []
    for line in stderr_s.splitlines():
        # Rust tracing format: "2026-05-09T...Z ERROR ..."
        if ' ERROR ' in line or ' WARN ' in line:
            lines.append(line)
        # Python/generic error formats; dsh writes "dsh: <code>: <message>"
        elif line.startswith(('Error:', 'error:', 'Traceback', 'Exception:', 'dsh:')):
            lines.append(line)
    return '\n'.join(lines)


def _linear_comment_body(*, title: str, prompt: str = "", output: str = "", error: str = "",
                         feedback: str = "", attachments: list[dict] | None = None) -> str:
    sections: list[str] = [f"**{title}**"]
    if feedback.strip():
        sections.append(feedback.strip())
    if prompt.strip():
        sections.append(f"**Prompt**\n```\n{prompt.strip()}\n```")
    if output.strip():
        sections.append(f"**Output**\n```\n{output.strip()}\n```")
    if error.strip():
        sections.append(f"**Error**\n```\n{error.strip()}\n```")
    attachment_lines = [
        f"- [{a.get('name') or a.get('filename') or 'attachment'}]({a.get('url', '')})"
        for a in (attachments or []) if a.get("url")
    ]
    if attachment_lines:
        sections.append("**Attachments**\n" + "\n".join(attachment_lines))
    return "\n\n".join(s for s in sections if s).strip()


def _is_image_attachment(name: str) -> bool:
    return Path(name).suffix.lower() in _IMAGE_SUFFIXES


def _format_prompt_attachments(attachments: list[dict] | None) -> str:
    lines = []
    uploads_root = BOARD_UPLOADS_DIR.resolve()
    for idx, attachment in enumerate(attachments or [], 1):
        name = attachment.get("name") or attachment.get("filename") or f"attachment-{idx}"
        filename = attachment.get("filename") or ""
        url = attachment.get("url") or ""
        local_path = ""
        if filename:
            candidate = (BOARD_UPLOADS_DIR / Path(filename).name).resolve()
            try:
                candidate.relative_to(uploads_root)
            except ValueError:
                candidate = None
            if candidate and candidate.exists():
                if _is_image_attachment(candidate.name):
                    lines.append(" | ".join([f"{idx}. {name}", "type: image", f"path: {candidate}"]))
                    continue
                local_path = str(candidate)
        elif attachment.get("path"):
            candidate = Path(str(attachment["path"])).resolve()
            try:
                candidate.relative_to(uploads_root)
            except ValueError:
                candidate = None
            if candidate and candidate.exists():
                if _is_image_attachment(candidate.name):
                    lines.append(" | ".join([f"{idx}. {name}", "type: image", f"path: {candidate}"]))
                    continue
                local_path = str(candidate)

        parts = [f"{idx}. {name}"]
        if local_path:
            parts.append(f"local path: {local_path}")
        if url:
            parts.append(f"url: {url}")
        lines.append(" | ".join(parts))
    if not lines:
        return ""
    return "\n\n[Attachments]\n" + "\n".join(lines)


