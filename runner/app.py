def _stream_text_run(
    proc: "subprocess.Popen[bytes]",
    run_id: str,
    timeout: float = 600,
    fmt: str = "text",
) -> tuple[str, str]:
    """Stream proc stdout line-by-line to a live log file. Returns (stdout_str, stderr_str).

    stderr collected at end only (kept separate for error parsing).
    Raises subprocess.TimeoutExpired if timeout exceeded.
    """
    stream_path = _claude_stream_log_path(run_id)
    RUN_PROGRESS_DIR.mkdir(parents=True, exist_ok=True)
    collected: list[str] = []
    stop = threading.Event()

    def _reader() -> None:
        with stream_path.open("a", encoding="utf-8") as sf:  # append: a fallback attempt keeps the first (UI-10)
            for raw in _iter_pipe_lines(proc.stdout, stop):
                line = raw.decode("utf-8", errors="replace").rstrip("\n")
                if line:
                    collected.append(line)
                    _persist_and_publish(run_id, fmt, sf, line)
                    _write_run_progress_json(run_id, {
                        "state": "running",
                        "stream_log": str(stream_path),
                        "last_event_type": "text",
                    })

    stderr_s = _read_both(proc, _reader, stop, timeout, run_id)
    return "\n".join(collected), stderr_s


def _shorten_pulse(text: str, limit: int = 96) -> str:
    text = " ".join(text.split())
    if len(text) <= limit:
        return text
    return "..." + text[-(limit - 3):]


def _load_log_pulse(limit: int) -> list[tuple[float, str]]:
    """Fallback activity from dated wiki log entries."""
    if not WIKI_LOG.exists():
        return []

    pattern = re.compile(r"^\s*-\s*(\d{4}-\d{2}-\d{2})(?:\s+(\d{2}:\d{2}))?\s+[—-]\s+(.*)$")
    entries: list[tuple[float, str]] = []
    for line in WIKI_LOG.read_text(encoding="utf-8").splitlines():
        match = pattern.match(line.strip())
        if not match:
            continue
        day, hhmm, body = match.groups()
        stamp = f"{day} {hhmm or '00:00'}"
        try:
            ts = datetime.strptime(stamp, "%Y-%m-%d %H:%M").timestamp()
        except ValueError:
            continue
        entries.append((ts, f"{stamp} - { _shorten_pulse(body) }"))

    return sorted(entries, reverse=True)[:limit]


def load_vault_pulse(limit: int = 8) -> list[str]:
    records: list[tuple[float, str]] = []
    for root_name in VAULT_PULSE_ROOTS:
        base = KNOWLEDGE_BASE_ROOT / root_name
        if not base.exists():
            continue
        for path in base.rglob("*.md"):
            if path == WIKI_LOG:
                continue
            if any(part.startswith(".") for part in path.relative_to(KNOWLEDGE_BASE_ROOT).parts):
                continue
            try:
                ts = path.stat().st_mtime
            except OSError:
                continue
            stamp = datetime.fromtimestamp(ts).strftime("%Y-%m-%d %H:%M")
            rel = path.relative_to(KNOWLEDGE_BASE_ROOT).as_posix()
            records.append((ts, f"{stamp} - {_shorten_pulse(rel)}"))

    if records:
        return [item for _, item in sorted(records, reverse=True)[:limit]]
    return [item for _, item in _load_log_pulse(limit)]


def build_chart_data(runs: list[dict], confidential_keys=frozenset()) -> dict:
    """Conversations per local day over 30 days, split three ways (AGE-128):
    agentic — AgenticOS itself: bound to agentic-os, or an unbound prompt (it runs in the
    runner's own checkout); work — a confidential project (the record's flag, or a project the
    registry now marks confidential, keys lowercase); other — everything else."""
    today = datetime.now().astimezone().date()
    days = [today - timedelta(days=i) for i in range(29, -1, -1)]
    counts = {name: {d: 0 for d in days} for name in ("agentic", "work", "other")}
    for run in runs:
        try:
            day = datetime.fromisoformat(run.get("started_at") or run.get("created_at") or "").astimezone().date()
        except Exception:
            continue
        if day not in counts["other"]:
            continue
        key = str(run.get("project_key") or run.get("session_project") or "").lower()
        if key == "agentic-os" or (not key and run.get("skill") == "_prompt"):
            name = "agentic"
        elif run.get("confidential") is True or key in confidential_keys:
            name = "work"
        else:
            name = "other"
        counts[name][day] += 1
    return {"labels": [d.strftime("%b %d") for d in days],
            **{name: [c[d] for d in days] for name, c in counts.items()}}


