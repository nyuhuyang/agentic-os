def _stream_claude_run(
    proc: "subprocess.Popen[bytes]",
    run_id: str,
    timeout: float = 600,
) -> tuple[str, int | None, int | None, str | None, str | None, str]:
    """Stream Claude stream-json stdout to a JSONL progress file.

    Returns (output, input_tokens, output_tokens, model, session_id, stderr).
    """
    stream_path = _claude_stream_log_path(run_id)
    RUN_PROGRESS_DIR.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    result_event: dict = {}
    session_id_holder: list[str | None] = [None]
    init_model: list[str | None] = [None]
    stop = threading.Event()

    def _reader() -> None:
        with stream_path.open("a", encoding="utf-8") as sf:  # append: a fallback attempt keeps the first (UI-10)
            for raw in _iter_pipe_lines(proc.stdout, stop):
                line = raw.decode("utf-8", errors="replace").rstrip("\n")
                if not line:
                    continue
                lines.append(line)
                _persist_and_publish(run_id, "claude", sf, line)
                try:
                    ev = json.loads(line)
                    if ev.get("type") == "result":
                        result_event.update(ev)
                    if ev.get("type") == "system" and ev.get("subtype") == "init" and ev.get("model"):
                        init_model[0] = init_model[0] or ev["model"]
                        _OBSERVED_MODELS[run_id] = init_model[0]  # for a timeout/cancel/stall record too (SBI-015)
                    if not session_id_holder[0] and ev.get("session_id"):
                        session_id_holder[0] = ev["session_id"]
                    _write_run_progress_json(run_id, {
                        "state": "running",
                        "stream_log": str(stream_path),
                        "last_event_type": ev.get("type", ""),
                    })
                except Exception:
                    pass

    stderr_s = _read_both(proc, _reader, stop, timeout, run_id)

    output = result_event.get("result", "")
    usage = result_event.get("usage") or {}
    model = _observed_claude_model(init_model[0], result_event)
    if not output and lines:
        output = lines[-1]
    session_id = session_id_holder[0] or result_event.get("session_id")

    _write_run_progress_json(run_id, {"stream_log": str(stream_path)})
    return output, usage.get("input_tokens"), usage.get("output_tokens"), model, session_id, stderr_s


def _stream_dsh_run(
    proc: "subprocess.Popen[bytes]",
    run_id: str,
    timeout: float = 1800,
) -> tuple[str | None, int | None, int | None, str | None, str | None, str]:
    """Stream `dsh --profile headless --json` NDJSON events to a JSONL progress file.

    Returns (output, input_tokens, output_tokens, model, session_id, stderr), like the other
    stream readers. output is the `final` text, or None when no `final` event arrived. When the
    run is not ok (exit != 0 or no final), stderr carries the composed "dsh: ..." error lines.
    Use _dsh_ok() for the success test. Model is always None: headless prints none.
    """
    stream_path = _claude_stream_log_path(run_id)
    RUN_PROGRESS_DIR.mkdir(parents=True, exist_ok=True)
    events = dsh_cli.DshRun()
    stop = threading.Event()

    def _reader() -> None:
        with stream_path.open("a", encoding="utf-8") as sf:  # append: a fallback attempt keeps the first (UI-10)
            for raw in _iter_pipe_lines(proc.stdout, stop):
                line = raw.decode("utf-8", errors="replace").rstrip("\n")
                if not line:
                    continue
                _persist_and_publish(run_id, "dsh", sf, line)
                ev = events.feed_line(line)
                if ev is None:
                    continue
                ev_type = ev.get("type", "")
                if _running_jobs.get(run_id):
                    _running_jobs[run_id]["last_progress_at"] = time.monotonic()
                progress = {"state": "running", "stream_log": str(stream_path), "last_event_type": ev_type}
                if ev_type == "tool_call":
                    tool_name = str(ev.get("tool") or "tool")
                    test_cmd = project_runs.test_command_of("dsh", line)  # AGE-140: keep the test note on the card
                    snippet = project_runs.test_note_text(test_cmd) if test_cmd \
                        else f"[tool] {tool_name}: {str(ev.get('input', {}))[:80]}"
                    socketio.emit("run_progress", {"run_id": run_id, "snippet": snippet, "event": "tool_use"})
                    progress["tool_name"] = tool_name
                elif ev_type == "tool_result":
                    socketio.emit("run_progress", {"run_id": run_id, "snippet": f"[tool_result] {ev.get('status', '')}",
                                                   "event": "tool_result"})
                _write_run_progress_json(run_id, progress)

    stderr_chunks: list[bytes] = []

    sink = _StderrSink(run_id)  # live and kept for replay, a timeout included (IR9-02)

    def _drain_stderr() -> None:  # concurrently, so a chatty stderr can never block the child
        for chunk in _iter_pipe_chunks(proc.stderr, stop):
            stderr_chunks.append(chunk)
            sink.feed(chunk)

    deadline = time.monotonic() + timeout
    readers: list[threading.Thread] = []
    errors: list[BaseException] = []
    try:
        for fn in (_reader, _drain_stderr):  # counted readers (BUILD-014), started inside the cleanup
            readers.append(_start_counted(_guarded(fn, errors), _thread=_REAL_THREAD))
        # Short slices: a failed reader surfaces at once, not after the other one's deadline.
        while not errors and any(r.is_alive() for r in readers) and time.monotonic() < deadline:
            for r in readers:
                r.join(timeout=min(0.25, max(0.0, deadline - time.monotonic())))
        if errors:  # a reader failed: same cleanup, then the error reaches the worker (RWS-019)
            raise errors[0]
        if any(r.is_alive() for r in readers):
            raise subprocess.TimeoutExpired(proc.args, timeout)
        proc.wait(timeout=max(0.0, deadline - time.monotonic()))
    except subprocess.TimeoutExpired:
        _timeout_cleanup(proc, stop, readers)
        raise subprocess.TimeoutExpired(proc.args, timeout)
    except BaseException:  # a reader could not start: stop the other, end the group (RWS-004)
        _timeout_cleanup(proc, stop, readers)
        raise
    finally:
        sink.close()
    stderr_s = b"".join(stderr_chunks).decode("utf-8", errors="replace").strip()
    ok, error_s = events.outcome(proc.returncode, stderr_s)
    input_tokens, output_tokens = events.tokens()
    _write_run_progress_json(run_id, {"stream_log": str(stream_path)})
    return events.final, input_tokens, output_tokens, None, events.session_id, (stderr_s if ok else error_s)


def _dsh_ok(proc: "subprocess.Popen[bytes]", output: str | None) -> bool:
    """dsh succeeded only with exit 0 AND a final event (it still prints final on a failed turn)."""
    return proc.returncode == 0 and output is not None


