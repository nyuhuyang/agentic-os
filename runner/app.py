_SHUTTING_DOWN = threading.Event()
_WITHHELD_PROMPT = "[withheld: run-record location not allowed for confidential runs]"

# Maintenance (scripts/relocate_checkout.sh): while set, no new run starts. Every run counts
# itself in-flight from admission until it returns, i.e. after its record is written, so the
# count also covers the gap between leaving _running_jobs and writing the record (BUILD-001).
_MAINTENANCE = threading.Event()
_INFLIGHT = 0
_INFLIGHT_LOCK = threading.Lock()


class MaintenanceRefused(RuntimeError):
    pass


_TL = threading.local()  # .admitted: this thread already works under a reservation


def _admit() -> None:
    """Reserve one in-flight slot for new work, or refuse under maintenance. Same lock as
    switching maintenance on, so work is either counted or refused."""
    global _INFLIGHT
    with _INFLIGHT_LOCK:
        if _MAINTENANCE.is_set():
            raise MaintenanceRefused("maintenance in progress (the checkout is being moved); try again shortly")
        _INFLIGHT += 1


def _release() -> None:
    global _INFLIGHT
    with _INFLIGHT_LOCK:
        _INFLIGHT -= 1


@contextlib.contextmanager
def _inflight_work():
    """Run the body counted; nested inside already admitted work it neither re-checks nor
    counts twice."""
    if getattr(_TL, "admitted", False):
        yield
        return
    _admit()
    _TL.admitted = True
    try:
        yield
    finally:
        _TL.admitted = False
        _release()


_REAL_THREAD = threading.Thread  # pipe readers always need a real thread to be able to time out


def _start_counted(target, *args, **kwargs) -> threading.Thread:
    """Every background writer starts here. Spawned from admitted work (a request, a counted
    worker) it takes its own slot even after admission closed, because its parent is still
    counted at that moment; spawned from anywhere else it must be admitted (BUILD-008). The
    slot is released when the thread ends, or at once if it cannot start (BUILD-009)."""
    global _INFLIGHT
    thread_cls = kwargs.pop("_thread", None) or threading.Thread
    if getattr(_TL, "admitted", False):
        with _INFLIGHT_LOCK:
            _INFLIGHT += 1
    else:
        _admit()

    def run():
        _TL.admitted = True
        try:
            target(*args, **kwargs)
        finally:
            _TL.admitted = False
            _release()
    try:  # construction and start both inside: either can fail after the slot was taken (BUILD-009)
        t = thread_cls(target=run, daemon=True)
        t.start()
    except BaseException:
        _release()
        raise
    return t


def _counted(fn):
    """A background run: counted while it works; refused (logged, nothing started) under maintenance."""
    @functools.wraps(fn)
    def wrapper(*a, **kw):
        try:
            with _inflight_work():
                return fn(*a, **kw)
        except MaintenanceRefused as exc:
            logger.warning("%s refused: %s", fn.__name__, exc)
            if kw.get("ticket_hold") is not None:  # a lock reserved for a launch that never ran
                kw["ticket_hold"].close()
            if kw.get("run_id"):
                _release_session(kw["run_id"])  # and its session claim (FB2-02)
            return {"status": "error", "error": str(exc)}
    return wrapper


@app.before_request
def _maintenance_gate():
    """Every mutating request is admitted (counted until it ends) or refused with 409 while
    maintenance is on, so no HTTP writer is mid-flight when the runner stops (BUILD-008)."""
    if request.method in ("GET", "HEAD", "OPTIONS") or request.path == "/api/maintenance" \
            or request.path.startswith("/socket.io"):
        return None
    try:
        _admit()
    except MaintenanceRefused as exc:
        return jsonify({"ok": False, "error": str(exc)}), 409
    g.aos_admitted = True
    _TL.admitted = True
    return None


@app.teardown_request
def _maintenance_release(_exc=None):
    if g.pop("aos_admitted", False):
        _TL.admitted = False
        _release()


@app.route("/api/maintenance", methods=["GET", "POST"])
def api_maintenance():
    if request.method == "POST":
        on = bool((request.get_json(silent=True) or {}).get("on"))
        with _INFLIGHT_LOCK:
            _MAINTENANCE.set() if on else _MAINTENANCE.clear()
    with _INFLIGHT_LOCK:
        return jsonify({"maintenance": _MAINTENANCE.is_set(), "inflight": _INFLIGHT})


def _stop_project_runs() -> None:
    """Shutdown (SIGTERM/atexit): refuse new processes, kill and reap every live one (git, agent,
    verify), then give the workers a moment to write their records (I5-12, I6-08). A generic run
    (run_agent_process) is cancelled here, record included, since its worker never reads the
    cancel flag; one already finalizing is waited for (STB §3.7, SBR-009/010)."""
    _SHUTTING_DOWN.set()
    with _JOB_LOCK:
        for job in list(_running_jobs.values()):
            if job.get("project_key") and job.get("phase") != "finalizing":
                job.setdefault("cancelled", "cancelled")
    _projects.stop_all()
    for rid, job in list(_running_jobs.items()):
        if not job.get("project_key"):
            with contextlib.suppress(Exception):
                _cancel_generic(rid, "Cancelled: dashboard shutting down")
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline and (_FINALIZING or any(j.get("project_key") for j in list(_running_jobs.values()))):
        time.sleep(0.1)


def _terminate_group(proc) -> None:
    """SIGTERM the group now, SIGKILL after 5 s while the leader is unreaped (I6-07)."""
    def _kill():
        if proc.poll() is None:
            with contextlib.suppress(ProcessLookupError, PermissionError):
                os.killpg(proc.pid, signal.SIGKILL)
    with contextlib.suppress(ProcessLookupError, PermissionError):
        os.killpg(proc.pid, signal.SIGTERM)
    timer = threading.Timer(5, _kill)
    timer.daemon = True
    timer.start()


_JOB_LOCK = threading.Lock()  # orders cancel/stall/shutdown against a run entering finalization


def _kill_group(proc, sig: int = signal.SIGKILL) -> None:
    """Signal a run's whole process group (started in its own session, so pgid == pid) so its
    descendants go with it (BUILD-014). No pid or no such group: signal just the process."""
    pid = getattr(proc, "pid", None)
    if pid:
        try:
            os.killpg(pid, sig)
            return
        except OSError:
            pass
    with contextlib.suppress(Exception):
        send = getattr(proc, "send_signal", None)
        send(sig) if send else proc.kill()


def _kill_and_reap(proc) -> None:
    """Kill the group and wait (bounded) for the leader, so no zombie waits on a later Popen (RWS-010)."""
    _kill_group(proc)
    with contextlib.suppress(Exception):
        proc.wait(timeout=5)


def _run_grouped(cmd, timeout: float, **kw) -> subprocess.CompletedProcess:
    """subprocess.run for an agent CLI call: its own process group, and on timeout or any failure
    the whole group is killed and reaped, not just the leader (RWS-016)."""
    proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, start_new_session=True, **kw)
    try:
        out, err = proc.communicate(timeout=timeout)
    except BaseException:
        _kill_and_reap(proc)
        raise
    _kill_group(proc)  # success too: nothing it started outlives the call (CM-023)
    return subprocess.CompletedProcess(cmd, proc.returncode, out, err)


class _RunEnded(Exception):
    """The run was cancelled or stalled before its process could be registered (WS-004)."""


def _register_proc(run_id: str, proc) -> bool:
    """Launch handshake (WS-004): publish the process only while its run is live. A run ended
    (cancel, stall) before or during Popen, or any launch once shutdown began (§3.7), has its new
    process killed and reaped here."""
    with _JOB_LOCK:
        if run_id in _running_jobs and not _SHUTTING_DOWN.is_set():
            old, _running_procs[run_id] = _running_procs.get(run_id), proc
            live = True
        else:
            live = False
    try:
        if live:
            if old is not None and old is not proc:
                _kill_group(old)  # the previous attempt's leftovers end with it (RWS-005)
            return True
        _kill_and_reap(proc)
        return False
    finally:
        with _JOB_LOCK:
            _LAUNCHING.pop(run_id, None)  # published (a live job again) or killed (CM-017)


# Runs whose worker won _end_job and has not written its record yet; shutdown waits for them.
# Added by _end_job, removed by _write_run_log once the run's record is on disk (SBR-010).
_FINALIZING: set[str] = set()
# Jobs a cancel or stall retired while their process group may still be stopping: a manual merge
# still counts them as activity until that path has stopped them and written the record (CM-011).
_RETIRING: dict[str, dict] = {}
# Runs between Popen and the _register_proc handshake: a cancel in that gap sees no process, so
# the child is activity until the handshake publishes or kills it (CM-017).
_LAUNCHING: dict[str, dict] = {}


def _end_job(run_id: str) -> bool:
    """Retire a run's job and process entries together (WS-006). True when the caller ended
    the run; False when cancel or stall already had, and so owns its terminal side effects."""
    with _JOB_LOCK:
        _mark_job_closing(run_id)  # leftovers of a finished run still block renames (R5-01)
        job = _running_jobs.pop(run_id, None)
        _running_procs.pop(run_id, None)
        if job is not None:
            _FINALIZING.add(run_id)  # its process has ended: not activity (only cancel/stall retire live groups, CM-019)
    return job is not None


def _cancel_generic(run_id: str, error: str) -> dict | None:
    """End a generic (run_agent_process) run as its owner: take job and process under the lock,
    SIGTERM then SIGKILL the group with reaping, and write the cancelled record before
    returning. The displaced worker then finds no job and writes nothing. None: not running
    (or already finishing). Used by cancel and by shutdown (SBR-010)."""
    with _JOB_LOCK:
        _mark_job_closing(run_id)  # before the job leaves the live set: no rename slips in (R3)
        job = _running_jobs.pop(run_id, None)
        proc = _running_procs.pop(run_id, None) if job is not None else None
        if job is not None:
            _RETIRING[run_id] = job  # until its record is written, after the group is gone (CM-011)
    if job is None:
        return None
    try:
        if proc is not None:
            _kill_group(proc, signal.SIGTERM)
            with contextlib.suppress(Exception):
                proc.wait(timeout=5)
            # Unconditional: a descendant ignoring SIGTERM outlives a leader that exited promptly (WS-002).
            # ponytail: the group id could in theory be reused within the grace; same ceiling as _terminate_group.
            _kill_group(proc)
            with contextlib.suppress(Exception):
                proc.wait(timeout=5)
        _write_owner_record(run_id, job, "cancelled", error, proc=proc)
    finally:
        _RETIRING.pop(run_id, None)  # stopped and recorded (or the record failed): never blocks merges forever
    return job


def _write_run_log_retrying(*args, **kwargs) -> None:
    """A terminal record written from a timeout/error handler, or by cancel/stall: tried twice and
    never raises, so the tracker completion after it still runs (RWS-003, RWS-006)."""
    for attempt in (1, 2):
        try:
            _write_run_log(*args, **kwargs)
            return
        except Exception:
            logger.exception("run record %s for %s failed (attempt %d)", args[1:2], kwargs.get("run_id"), attempt)


def _comment_quietly(post, *args) -> None:
    """A run's closing tracker comment is optional: its failure is logged and never skips the
    tracker completion after it (RWS-013)."""
    try:
        post(*args)
    except Exception:
        logger.exception("closing tracker comment failed")


def _write_owner_record(run_id: str, job: dict, status: str, error: str, proc=None) -> None:
    """Terminal record by the party that ended a run (cancel, stall). It carries the launch's
    metadata (job["record"]), so a retry of it keeps its task, ancestry and agent (RWS-002).
    Tried twice: the displaced worker writes nothing, so a lost record loses the run (RWS-003).
    `proc`: the run's signalled process; until its group is gone, its session is not renamed (R6)."""
    meta = {"linear_issue_id": job.get("linear_issue_id"), **job.get("record", {})}
    sid = job.get("agent_session_id") or (_SESSION_CLAIMS.get(run_id) or (None, None))[1]
    if sid:  # a cancelled/stalled run stays resumable (UI2-04)
        meta.setdefault("agent_session_id", sid)
    agent = meta.get("agent") or job.get("agent")
    pgid = getattr(proc, "pid", None)
    _mark_closing(agent, sid, pgid)  # before the record: no trigger renames a session still exiting
    # A session card's routing and binding go with it, so the next reply routes the same (SBR-005).
    extra = job.get("record_extra")
    prompt = job.get("prompt", "")
    unsafe = extra and extra.get("project_key") and extra.get("confidential") is not False and _records_unsafe()
    if unsafe:
        prompt, error = _WITHHELD_PROMPT, f"withheld ({status}): run records are outside this checkout's ignored state/ or outputs/"
    if extra and unsafe and "issue_title" in extra:
        extra = {k: v for k, v in extra.items() if k != "issue_title"}  # withheld like the prompt (DP-24)
    started = _parse_run_started_at(job.get("started_at"))
    # the real elapsed time, so the card's own last activity ends at the cancel or stall (DP-27)
    dur = max(0.0, (datetime.now(timezone.utc) - started).total_seconds()) if started else 0.0
    _write_run_log_retrying(job.get("skill", "unknown"), status, job.get("started_at", ""), dur,
                            prompt=prompt, error=error, run_id=run_id, extra=extra, **meta)
    _after_card_run(run_id, meta.get("linear_issue_id"), agent, sid, pgid)


class _RunClaim:
    """A worker's claim on its run's terminal side effects, taken once and kept through error
    recovery, so a failed record write is not mistaken for someone else's claim (WS-009)."""

    def __init__(self, run_id: str):
        self.run_id = run_id
        self.owner: bool | None = None
        self.session: str | None = None  # the job's last announced/claimed session, kept for its record (REV-02)

    def __call__(self) -> bool:
        if self.owner is None:
            job = _running_jobs.get(self.run_id) or {}
            self.session = job.get("agent_session_id") or (_SESSION_CLAIMS.get(self.run_id) or (None, None))[1]
            self.owner = _end_job(self.run_id)
        return self.owner


def _signal_project_run(run_id: str, why: str) -> str | None:
    """Cancel or stall a project run: flag it and stop its current phase's process group.
    The launch helper reaps the group and writes the record with the full binding (I5-01/09).
    Returns None (not a project run), "finishing" (too late: the outcome is decided, I8-06)
    or "ok"."""
    job = _running_jobs.get(run_id)
    if not job or not job.get("project_key"):
        return None
    with _JOB_LOCK:
        if job.get("phase") == "finalizing":
            return "finishing"
        job.setdefault("cancelled", why)
    proc = _running_procs.get(run_id)
    if proc is not None:
        _terminate_group(proc)
    return "ok"


@_counted
def _run_project_ticket(**kw) -> dict:
    """Holds the project's shared lifecycle lock for the whole launch, through its comment and
    running-job removal, so remove and lifecycle edits wait for it (REGUI-004, REGUI-006). An
    invalid key takes no lock; the helper's registry lookup then records the error."""
    with contextlib.ExitStack() as stack:
        stack.callback(_release_session, kw.get("run_id"))  # a resume claimed by the route ends here
        if kw.get("ticket_hold") is not None:
            stack.callback(kw["ticket_hold"].close)  # the card lock reserved by the retry route
        with contextlib.suppress(_projects.ProjectError):
            stack.enter_context(_projects.project_lock(kw["project_key"]))
        return _run_project_ticket_locked(**kw)


def _run_project_ticket_locked(*, project_key: str, ident: str, agent: str, prompt: str, title: str,
                               run_id: str, linear_issue_id: str | None, task_id: str, launch_gen: int,
                               attempt: int = 0, parent_run_id: str | None = None,
                               resume_session: str | None = None, reuse_only: bool = False,
                               skill: str = "_prompt", confidential: bool | None = None,
                               ticket_hold: contextlib.ExitStack | None = None,
                               record_extra: dict | None = None, timeout: float | None = None,
                               note: str | None = None) -> dict:
    """The one launch helper for every project-bound launch (dispatch and retry/rework).

    Holds the ticket lock across worktree -> agent -> runner commit -> verify -> seed check
    -> closing fingerprint. Fails closed: a refused backend, a missing binding or a missing
    worktree ends as an error record, never as a launch at the runner root. `confidential` is
    the persisted flag (None = unknown); it never weakens, and unknown is treated as
    confidential for tracker comments (I5-02). Cancel, stall and shutdown only flag the job;
    this helper writes every record, so each carries the binding (I5-01).
    `timeout`: a session continuation passes AI_SESSION_TIMEOUT_S (D7); `note`: why this run
    started a new session, written first into its stream (DP-39)."""
    started_at = datetime.now(timezone.utc).isoformat()
    t0 = time.monotonic()
    timeout = AI_RUN_TIMEOUT_S if timeout is None else timeout
    agent_pgid: list = [None]  # the agent's process group, for the run-end name sync (R6)
    gen_key = linear_issue_id or task_id
    stored = _durable_binding(linear_issue_id, task_id, project_key, ident) or {}
    confidential = _ticket_confidential(project_key, ident, linear_issue_id, task_id,
                                        *([confidential] if confidential is not None else []))
    binding: dict = {"project_key": project_key, "issue_identifier": ident, "confidential": confidential}
    record_kw = dict(run_id=run_id, linear_issue_id=linear_issue_id, agent=agent, task_id=task_id,
                     attempt=attempt, parent_run_id=parent_run_id, reset_generation=launch_gen,
                     model=_agent_model(agent))
    job = _running_jobs[run_id] = {
        "run_id": run_id, "skill": skill, "started_at": started_at, "prompt": prompt, "state": "running",
        "last_progress_at": time.monotonic(), "linear_issue_id": linear_issue_id, "agent": agent,
        "project_key": project_key, "phase": "agent"}
    socketio.emit("run_state_change", {"run_id": run_id, "state": "running", "skill": skill})
    status, output, error, result, sid, it, ot, model = "error", "", "", {}, None, None, None, None
    lines: list[str] = []  # the raw agent stream, for the last-message extraction below

    def _track(proc):
        _running_procs[run_id] = proc
        if agent_pgid[0] is None:
            agent_pgid[0] = getattr(proc, "pid", None)
        if job.get("cancelled"):  # cancelled between phases: stop this one too
            _terminate_group(proc)

    def _emit(event, payload):
        job["last_progress_at"] = time.monotonic()  # streaming agent = progress (I5-07)
        line = re.sub(r"\x1b\[[0-9;]*m", "", str((payload or {}).get("line") or "")) \
            if isinstance(payload, dict) else ""
        if event == "run_event" and (project_runs.TEST_NOTE_MARK in line or "[tool]" in line):
            # AGE-140: the test heads-up and later tool calls both keep the card's status line current.
            snippet = line.replace("[runner] ", "").strip()
            socketio.emit("run_progress", {"run_id": run_id, "snippet": snippet, "event": "tool_use"})
        socketio.emit(event, payload)

    try:
        if _SHUTTING_DOWN.is_set():
            raise project_runs.ProjectRunError("runner is shutting down")
        if linear_issue_id and not _card_admitted(linear_issue_id, launch_gen):
            # gone or reset while queued: no launch (R4, R3-01)
            raise _projects.ProjectError("this card was removed or reset before its run started")
        errors: dict = {}
        project = _projects.get_project(project_key, _projects.load_registry(errors=errors))
        # Resolved above. Unknown (an unreadable sidecar) stays None: treated as confidential
        # here and in every outbound path, never collapsed to False (I10-01).
        if binding["confidential"] is not False:
            # One effective policy: a ticket once confidential stays sandboxed even if the
            # registry flag was dropped since (I6-02).
            project = dataclasses.replace(project, confidential=True)
            problem = _records_unsafe()  # registry may have changed since startup (I5-04)
            if problem:
                raise _projects.ProjectError(problem)
        keys = _binding_keys(linear_issue_id, task_id, project.key, ident)
        _persist_binding(keys, {"project_key": project.key, "issue_identifier": ident,
                                "confidential": binding["confidential"]})
        # A retry route already holds this ticket (reserved before its tracker changes, C2).
        with contextlib.nullcontext() if ticket_hold is not None else _projects.ticket_lock(project.key, ident):
            if reuse_only and not _projects.worktree_path(project, ident).exists():
                raise _projects.ProjectError(
                    f"{project.key}/{ident}: bound worktree is missing; refusing to fall back "
                    "(remove its entries from state/issue_bindings.json to start over)")
            wt_info = _projects.create_worktree(project, ident)
            for field_ in ("worktree", "branch", "base_sha"):  # the whole binding, not just the base (I7-06)
                if stored.get(field_) and stored[field_] != wt_info[field_]:
                    raise _projects.ProjectError(f"{project.key}/{ident}: {field_} differs from the first run's binding; "
                                                 "refusing to continue (recover explicitly)")
            if binding["confidential"] is not False:
                _projects.mark_confidential(project, ident)
            binding.update(project_runs.binding_fields(project, ident, wt_info))
            _persist_binding(keys, {k: binding[k] for k in ("worktree", "branch", "base_sha")})
            run_start_sha = None  # HEAD just before the agent: "this run changed nothing" (§7)
            with contextlib.suppress(Exception):
                wt_path = Path(binding["worktree"])
                run_start_sha = _projects._git(wt_path, "rev-parse", "HEAD",
                                               confine=_projects.confine_for(project, wt_path)).stdout.strip() or None
            exclude = project_runs.bookkeeping_paths(project, [STATE_DIR, OUTPUTS_DIR])
            with _merge_gate(project.key):  # never between a queued merge's check and its merge (SC-019)
                parts = _projects.fingerprint_parts(project, exclude=exclude)
                with _JOB_LOCK:
                    _RUN_BASELINES[run_id] = {"key": project.key, "project": project, "exclude": exclude,
                                              "parts": parts, "changed": False}

            def closing() -> dict:
                """The closing fingerprint against the baseline as a manual merge/commit left it (AGE-124)."""
                with _merge_gate(project.key):
                    with _JOB_LOCK:
                        base = _RUN_BASELINES.pop(run_id, None)
                    if base is None:  # fail closed, like an unreadable snapshot (I7-07)
                        return {"main_checkout_changed": None, "closing_check_error": "no opening fingerprint"}
                    out = project_runs.closing_check(project, exclude, _projects.fingerprint_of(base["parts"]))
                if base["changed"] and out["main_checkout_changed"] is False:
                    out["main_checkout_changed"] = True  # changed before or during a sanctioned change (R05)
                return out
            tab_open = _main_path_tab_open(project.key)
            # AGE-137: a fresh run gets the ticket's earlier-run notes. A resumed session already
            # has its own context, and a confidential prompt never reaches the wiki.
            memory_brief = "" if (resume_session or project.confidential) else ai_memory.brief(project.key, ident)
            prompt_text = project_runs.project_prompt(prompt, project, binding, agent)
            cmd = _project_cmd(agent, project,
                               project_runs.with_memory_brief(prompt_text, memory_brief),
                               resume_session)
            if resume_session:
                job["agent_session_id"] = resume_session  # in the live set before launch (A, R02)
            # Durable log for the run view's replay: a confidential run's log is written only
            # where its run records may go (already checked above), never elsewhere (C, R06).
            log_path = _claude_stream_log_path(run_id)
            log_path.parent.mkdir(parents=True, exist_ok=True)
            write_json_atomic(_stream_meta_path(run_id), {"format": agent})
            sink = _StderrSink(run_id)  # written only where this run's log may be (checked above)
            exec_env = _project_exec_env(agent, project, binding["worktree"], run_id)
            try:
                lines, stderr_s, code, timed_out = project_runs.run_agent(
                    cmd, binding["worktree"], exec_env, run_id, agent,
                    timeout, _emit, on_start=_track,
                    on_session=lambda sid: job.update(agent_session_id=sid), log_path=log_path,
                    on_stderr=sink.feed, note=note)  # stderr live as it arrives (IR9-02)
            finally:
                sink.close()
                _cleanup_dsh_spill(exec_env)
            _running_procs.pop(run_id, None)
            output, it, ot, model, sid, ok, error = _parse_project_output(agent, lines, stderr_s, code)
            agent_error, turn_failed = project_runs.pop_agent_failure(run_id)
            ok = ok and not turn_failed  # e.g. a Codex turn.failed with exit 0 (R4-03)
            replied = project_runs.pop_replied(run_id)
            if ok and resume_session and not replied:
                ok = False  # a continuation that said nothing is no success (DSI-01)
                error = error or f"resume of session {resume_session} failed (no reply)"
            if not ok and agent_error:
                error = agent_error  # the agent's own reason, e.g. a usage limit or turn.failed (D6, DP-44)
            if timed_out:
                status, error = "timeout", f"Timed out after {int(timeout)}s"
            else:
                status = "review" if ok else "error"
            if job.get("cancelled"):  # skip the work, keep the safety check (I6-13, I7-07)
                result = closing()
                if result["main_checkout_changed"] is None:
                    result["verify_badge"] = "main checkout unchecked"
                elif result["main_checkout_changed"]:
                    result["verify_badge"] = "main checkout changed"
            else:
                job["phase"] = "post_run"  # bounded by git/verify timeouts; not a stall candidate
                result = project_runs.post_run(project, binding, agent, title, None, exclude, closing=closing,
                                               on_start=_track, stopped=lambda: bool(job.get("cancelled")),
                                               start_sha=run_start_sha)
                if result.get("post_run_error"):
                    status, error = "error", result["post_run_error"]
                tab_open = tab_open or _main_path_tab_open(project.key)
                result["interactive_tab_open"] = tab_open
                if tab_open and result.get("verify_badge") == "main checkout changed":
                    result["verify_badge"] = "main checkout changed (interactive tab open)"
                result.update(_merge_when_last(project, ident, job, eligible=status == "review"
                                               and not job.get("cancelled")
                                               and result.get("verify_badge") in (None, "pass", "no check")))
    except (_projects.ProjectError, project_runs.ProjectRunError) as exc:
        status, error = "error", str(exc)
    except Exception as exc:
        logger.exception("project run %s failed", run_id)
        status, error = "error", str(exc)
    finally:
        _running_procs.pop(run_id, None)
        with _JOB_LOCK:  # from here a cancel is refused, so the outcome below is final (I8-06)
            job["phase"] = "finalizing"
            _RUN_BASELINES.pop(run_id, None)  # a run that failed before its closing check
            cancelled = job.get("cancelled")
    try:  # the job stays registered until its record is written: shutdown waits for it (I7-03)
        if cancelled:  # authoritative through final logging: no review push, no run comment (I5-09)
            status, error = cancelled, "Cancelled by user" if cancelled == "cancelled" else "stalled"
        verify = result.get("verify")
        # record_extra: a session card's routing (resume_session, source), merged into the record (SBR-001)
        extra = {**(record_extra or {}), **binding, **{k: v for k, v in result.items() if k != "verify_tail"},
                 **_issue_title_extra(linear_issue_id, binding["confidential"]),
                 **({"session_note": note} if note else {})}
        if verify:
            extra["verify"] = verify
        withhold = binding["confidential"] is not False and _records_unsafe()
        if withhold:
            extra.pop("issue_title", None)  # withheld like the prompt (DP-24)
        if withhold:  # never write confidential text where records may leak (I5-04, I6-05)
            prompt_rec, output_rec = "[withheld: run-record location not allowed for confidential runs]", ""
            error = f"withheld ({status}): run records are outside this checkout's ignored state/ or outputs/"
        else:
            prompt_rec = prompt
            output_rec = (output or "") + (f"\n\n[verify tail]\n{result['verify_tail']}" if result.get("verify_tail") else "")
        # The memory service's bearer token is not part of any run record; scrub it from every
        # textual field the runner persists (the agent's own stream is separate).
        prompt_rec = ai_memory.scrub_token(prompt_rec)
        output_rec = ai_memory.scrub_token(output_rec)
        error = ai_memory.scrub_token(error)
        extra = ai_memory.scrub_record(extra)
        # AGE-137: leave the next agent (often another provider) the run's outcome. Unknown
        # confidentiality is treated like confidential: never write a prompt-derived summary.
        if binding["confidential"] is False:
            ai_memory.record_run(project_key, ident, run_id=run_id, agent=agent, status=status, title=title,
                                 summary=project_runs.closing_summary(agent, lines) or output,
                                 verify=verify, result=result)
        # a continuation keeps its session even when none was observed (failed early, timeout, SBI-011)
        _write_run_log(skill, status, started_at, time.monotonic() - t0, prompt=prompt_rec, output=output_rec,
                       error=error, input_tokens=it, output_tokens=ot, agent_session_id=sid or resume_session,
                       token_cost_usd=_compute_token_cost(ot, it, model or record_kw["model"]),  # STB-034
                       extra=extra, **{**record_kw, "model": model or record_kw["model"]})
        if linear_issue_id:
            if not cancelled:
                body = project_runs.tracker_comment(
                    binding, "Run", run_id=run_id, status=status, verify=verify, shortstat=result.get("shortstat", ""),
                    fallback=lambda: _linear_comment_body(title="AgenticOS Run", prompt=prompt, output=output, error=error))
                if body:
                    _post_linear_comment(linear_issue_id, body)
            _push_linear_state_async(linear_issue_id, "review", gen=launch_gen)
        if reset_gen.is_current(gen_key, launch_gen):
            socketio.emit("run_state_change", {"run_id": run_id, "state": status, "skill": skill})
        socketio.emit("run_logged", {"skill": skill, "run_id": run_id})
        return {"status": status, "error": error, **extra}
    finally:
        with _JOB_LOCK:  # the closing marker first, then the job leaves the live set (R5-01)
            _mark_closing(agent, sid or resume_session, agent_pgid[0])
            _running_jobs.pop(run_id, None)
        # after the record and the job's removal; the group was reaped by run_agent (§2 triggers)
        _after_card_run(run_id, linear_issue_id, agent, sid or resume_session, agent_pgid[0])


_PENDING_MERGES: dict[str, list[tuple[str, str]]] = {}  # project key -> (ticket, verified sha) waiting for its other runs (AGE-111)

# run_id -> {key, project, exclude, parts, changed}: each open project-bound run's opening main-checkout
# fingerprint by component, from its opening to its closing check (AGE-124). Never in the job dict:
# /api/runs serialises jobs. Written under the checkout's merge gate and _JOB_LOCK.
_RUN_BASELINES: dict[str, dict] = {}
# The components a manual merge or a main-checkout commit may move. Never config, hooks, refs, the
# branch, ignored files or the index flags (skip-worktree / assume-unchanged): those stay an agent's change.
_SANCTIONED = {"merge": {"head", "tracked"}, "commit": {"head", "tracked", "staged", "unstaged", "untracked"}}


def _explained(b: dict, op: str, pre: dict, post: dict, expect: dict) -> bool:
    """`post` is exactly what the operation made of `pre`: nothing outside its components moved,
    HEAD is the commit it reported, whose parents are exactly `pre`'s HEAD (plus the branch tip
    for a merge; a fast-forward merge is the tip itself), and a commit left nothing staged, changed or untracked behind (AGE124-I01/I02)."""
    if any(post[c] != pre[c] for c in pre if c not in _SANCTIONED[op]):
        return False
    head = expect.get("head")
    if head is None:  # nothing was committed or merged: nothing may have moved
        return post == pre
    if post["head"] != head:
        return False
    if post == pre and head == pre["head"]:  # already up to date: a no-op is no change (AGE124-I04)
        return True
    root, confine = b["project"].path, _projects.confine_for(b["project"])
    parents = _projects._git(root, "rev-parse", f"{head}^@", check=False, confine=confine).stdout.split()
    # every parent, not just the first: no extra history rides in on a same-tree commit (AGE124-I06)
    made = parents == ([pre["head"], expect.get("tip")] if op == "merge" else [pre["head"]])
    fast_forward = (op == "merge" and head == expect.get("tip") and _projects._git(
        root, "merge-base", "--is-ancestor", pre["head"], head, check=False, confine=confine).returncode == 0)
    if not made and not fast_forward:
        return False
    return op == "merge" or all(post[c] == v for c, v in _projects.CLEAN_PARTS.items())


@contextlib.contextmanager
def _rebase_bound_runs(project, op: str):
    """A main-checkout change the user asked for (a manual merge or commit) is not blamed on the
    checkout's open project-bound runs: their baselines move to the new state. Caller holds the
    checkout's merge gate, which every opening and closing fingerprint also takes. A run whose
    checkout had already changed, or whose other components move meanwhile (an agent writing a
    hook during the merge), is marked changed for good; nothing moves if the change raises."""
    keys = _same_checkout_keys(project.key)
    with _JOB_LOCK:
        runs = [b for b in _RUN_BASELINES.values() if b["key"] in keys and not b["changed"]]
    clean, expect = [], {}  # the operation fills expect: {"head": its commit, "tip": a merged branch tip}
    for b in runs:
        try:
            pre = _projects.fingerprint_parts(b["project"], b["exclude"])
        except Exception:
            pre = None
        if pre != b["parts"]:  # already changed (or unreadable): never laundered by this change (R05)
            b["changed"] = True
        else:
            clean.append((b, pre))
    yield expect
    for b, pre in clean:
        try:
            post = _projects.fingerprint_parts(b["project"], b["exclude"])
            ok = _explained(b, op, pre, post, expect)
        except Exception:
            ok = False
        if ok:
            b["parts"] = post
        else:
            b["changed"] = True


_MERGE_GATES: dict[str, threading.Lock] = {}
_MERGE_GATES_GUARD = threading.Lock()


def _merge_gate(key: str) -> threading.Lock:
    """Per-checkout gate: a queued or manual merge holds it from its "no other run is open" check to
    the end of the merge (including any wait on the global merge lock); a run takes it around its
    opening fingerprint or job publish, so none can start in between (SC-019, CM-013). Keyed by the
    checkout, so two registrations of one folder share it (CM-018). Lock order: ticket -> gate."""
    gate_id = _registry_checkouts().get(key) or f"key:{key}"
    with _MERGE_GATES_GUARD:
        return _MERGE_GATES.setdefault(gate_id, threading.Lock())


_ROOT_ACTIVE = 0  # runner-root work that is not a job, e.g. a Linear routing call (CM-013); under _JOB_LOCK


_ROOT_KEY_CACHE: dict = {}


def _registry_checkouts() -> dict[str, str]:
    """key -> real checkout path, from the registry file only (no git, no validation: this runs on
    every job publish and merge check), cached by its mtime."""
    path = _projects.REGISTRY_PATH
    try:
        stamp = (str(path), path.stat().st_mtime_ns)
    except OSError:
        return {}
    if _ROOT_KEY_CACHE.get("stamp") != stamp:
        out: dict[str, str] = {}
        entries: dict = {}
        with contextlib.suppress(Exception):
            entries = _projects.raw_entries(_projects._read_registry_bytes(path))
        for k, entry in entries.items():  # one bad entry never hides the others (CM-025)
            raw = entry.get("path") if isinstance(entry, dict) else None
            if isinstance(raw, str) and raw:
                with contextlib.suppress(Exception):
                    out[k] = os.path.realpath(os.path.expanduser(raw))
        _ROOT_KEY_CACHE.update(stamp=stamp, paths=out)
    return _ROOT_KEY_CACHE["paths"]


def _same_checkout_keys(key: str) -> set[str]:
    """Every registered key that names the same checkout as `key` (CM-018), `key` included."""
    paths = _registry_checkouts()
    mine = paths.get(key)
    return {key} | ({k for k, p in paths.items() if p == mine} if mine else set())


def _runner_root_key() -> str | None:
    """A registered project whose folder is the runner's own checkout, if any."""
    root = os.path.realpath(_PROTO)
    return next((k for k, p in _registry_checkouts().items() if p == root), None)


def _checkout_gate(path) -> threading.Lock | contextlib.nullcontext:
    """The merge gate of the registered checkout that contains `path` (longest match), or the
    runner-root gate when none does: a tab is gated by where it really runs (CM-028)."""
    real = os.path.realpath(str(path))
    best = None
    for k, p in _registry_checkouts().items():
        if (real == p or real.startswith(p.rstrip("/") + "/")) and (best is None or len(p) > len(best[1])):
            best = (k, p)
    return _merge_gate(best[0]) if best else _runner_root_gate()


def _runner_root_gate():
    key = _runner_root_key()
    return _merge_gate(key) if key else contextlib.nullcontext()


def _publish_job(run_id: str, job: dict) -> dict:
    """Publish a runner-root job (free prompt, generic retry, unbound dispatch) under the runner
    checkout's merge gate: it can never appear between a manual merge's check and its merge (CM-013)."""
    with _runner_root_gate():
        _running_jobs[run_id] = job
    return job


@contextlib.contextmanager
def _root_activity():
    """Runner-root work that is not a published job (a routing call) counts as activity too."""
    global _ROOT_ACTIVE
    with _runner_root_gate():
        with _JOB_LOCK:
            _ROOT_ACTIVE += 1
    try:
        yield
    finally:
        with _JOB_LOCK:
            _ROOT_ACTIVE -= 1


def _project_runs_open(key: str, job: dict | None, sessions: bool = False, runner_root: bool = False,
                       bound: bool = True) -> bool:
    """Another run of this project is still before its closing fingerprint: a merge now would
    read as that run changing the main checkout. Caller holds _JOB_LOCK.
    Used under _merge_gate, which a new run's opening fingerprint also takes (SC-019)."""
    # every registration of this checkout for a manual merge (CM-018); the auto-drain stays per key,
    # like its queue, so one registration's queued merge is never stranded by another's run (CM-022)
    keys = _same_checkout_keys(key) if sessions else {key}

    def here(j):
        extra = j.get("record_extra") or {}
        return ((bound and j.get("project_key") in keys)
                # an agent working in the main checkout itself (a session card, no project_key) (CM-004)
                or (sessions and extra.get("session_project") in keys)
                # a runner-root job (free prompt, generic retry, unbound dispatch) when the project IS the runner's checkout (CM-010)
                or (runner_root and not j.get("project_key") and not extra.get("session_project")))
    # retiring: still stopping (CM-011); launching: between Popen and its handshake (CM-017)
    jobs = list(_running_jobs.values()) + (list(_RETIRING.values()) + list(_LAUNCHING.values()) if sessions else [])
    if runner_root and _ROOT_ACTIVE:
        return True
    return any(j is not job and not j.get("merge_checked") and here(j) for j in jobs)


@contextlib.contextmanager
def _wait_ticket_lock(key: str, ident: str, timeout: float = 120.0):
    """Another finished ticket's lock, waiting for its run's finalization (log, tracker comment)
    to release it. No deadlock: only one run drains the queue, and a finalizing holder never
    needs the drainer's lock. Raises TicketLocked after `timeout` (SC-010)."""
    end = time.monotonic() + timeout
    with contextlib.ExitStack() as stack:
        while True:  # only the acquire is retried, never the caller's body
            try:
                stack.enter_context(_projects.ticket_lock(key, ident))
                break
            except _projects.TicketLocked:
                if time.monotonic() >= end:
                    raise
                time.sleep(0.5)
        yield


def _merge_when_last(project, ident: str, job: dict, eligible: bool) -> dict:
    """Merge finished ticket branches into the project's main checkout (AGE-111), only once no
    other run of the project is still before its closing fingerprint: a merge under it would
    read as that run changing the main checkout. Until then a ticket waits in _PENDING_MERGES
    and the project's last finishing run merges it.
    ponytail: the queue is in memory; a runner restart drops it (the branches stay, merge by hand)."""
    if not project.auto_merge:
        return {}
    # The commit that passed verification, read under this ticket's lock: a later commit on the
    # branch (a manual Commit, a terminal) never rides in on this verification (SC-007).
    head, head_error = None, None
    if eligible:
        try:
            head = _projects.branch_head(project, ident)
        except _projects.ProjectError as exc:
            head_error = str(exc)[:500]
    with _JOB_LOCK:
        job["merge_checked"] = True
        if head:
            _PENDING_MERGES.setdefault(project.key, []).append((ident, head))
        busy = _project_runs_open(project.key, job)
        todo = [] if busy else list(dict(_PENDING_MERGES.pop(project.key, [])).items())  # newest sha per ticket
    out: dict = {"merge_error": {ident: head_error}, "verify_badge": "merge failed"} if head_error else {}
    if busy:
        return out or ({"merge": "waiting for this project's other runs"} if eligible else {})
    def keep(entries):  # back in the queue for the project's next run; a newer one queued meanwhile wins (SC-013)
        with _JOB_LOCK:
            queue = _PENDING_MERGES.setdefault(project.key, [])
            for t, sha in entries:
                if not any(q == t for q, _ in queue):
                    queue.append((t, sha))
        for t, _ in entries:
            out.setdefault("merge", f"{t} waits for this project's next run")

    for n, (t, sha) in enumerate(todo):
        try:
            # another ticket's entry: re-check it under its own lock, since it may have been cleaned
            # up or re-run since it queued (SC-009); ours is held by this run already
            with contextlib.nullcontext() if t == ident else _wait_ticket_lock(project.key, t), _merge_gate(project.key):
                with _JOB_LOCK:
                    opened = _project_runs_open(project.key, job)
                if opened:  # a run opened (e.g. during a wait): no merge under its fingerprint, ours included (SC-016/018)
                    keep(todo[n:])
                    break
                eff = _effective_project(project, t)  # that ticket's own sticky policy, not the drainer's (SC-012)
                _projects.check_queued_merge(eff, t, sha)
                out["merged_head"] = _projects.merge_into_checkout(eff, t, sha)  # still under the gate
            out.setdefault("merged", []).append(t)
        except _projects.TicketLocked:
            keep([(t, sha)])  # its run is still finishing (SC-010)
        except _projects.ProjectError as exc:
            out.setdefault("merge_error", {})[t] = str(exc)[:500]
    if ident in out.get("merge_error", {}):
        out["verify_badge"] = "merge failed"
    return out


def _reset_key(records: list[dict], task_id: str) -> str:
    """Reset generations are kept per tracker issue when there is one, else per task."""
    return next((r["linear_issue_id"] for r in records if r.get("linear_issue_id")), None) or task_id


def _build_resume_cmd(agent: str, session_id: str, prompt: str) -> list[str]:
    """Build the agent-specific --resume command for a given session."""
    base = _ai_cli(agent)
    if agent == "claude":
        return base + ["--resume", session_id, "--output-format", "stream-json", prompt]
    if agent == "codex":
        return base + ["resume", session_id, prompt]
    if agent == "dsh":
        return base + ["--json", "--session-id", session_id, "--", prompt]
    return base + [prompt]


def _extract_skill_name(raw: str, registry: dict) -> str:
    normalized = (raw or "").strip().lower().replace(" ", "-")
    if normalized in registry:
        return normalized
    for line in (raw or "").splitlines():
        candidate = line.strip().lower().replace(" ", "-")
        if candidate in registry:
            return candidate
    for name in registry:
        if name in normalized:
            return name
    return list(registry.keys())[0] if registry else "_prompt"


