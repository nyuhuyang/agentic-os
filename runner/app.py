def _load_runs_from(path: Path, limit: int = 20, include_archived: bool = False) -> list[dict]:
    if not path.exists():
        return []
    lines = path.read_text(encoding="utf-8").strip().splitlines()
    seen: set[str] = set()
    records = []
    for line in reversed(lines):
        try:
            r = json.loads(line)
            if "run_id" not in r:
                h = hashlib.md5(f"{r.get('started_at','')}{r.get('skill','')}".encode()).hexdigest()[:8]
                r["run_id"] = f"legacy-{h}"
            r.setdefault("output_path", "")
            run_id = r["run_id"]
            if run_id in seen:
                continue  # dedup: latest append wins
            seen.add(run_id)
            if not include_archived and r.get("status") == "archived":
                continue  # mark seen for dedup, but exclude from normal results
            records.append(r)
        except Exception:
            continue
        if len(records) >= limit:
            break
    return records


# ── Runs cache (TTL 3s, avoids re-reading file on every API call) ──
_runs_cache: dict[str, tuple[float, list[dict]]] = {}
_RUNS_CACHE_TTL = 3.0  # seconds

def load_runs(limit: int = 20, include_archived: bool = False) -> list[dict]:
    """Load runs from RUN_LOG (superset of all records), fall back to state."""
    now = time.monotonic()
    key = f"{limit}:{include_archived}"
    cached = _runs_cache.get(key)
    if cached and (now - cached[0]) < _RUNS_CACHE_TTL:
        return cached[1]
    runs = _load_runs_from(RUN_LOG, limit, include_archived)
    if not runs:
        runs = _load_runs_from(STATE_RUN_LOG, limit, include_archived)
    _runs_cache[key] = (now, runs)
    return runs


