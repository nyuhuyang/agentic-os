def _fmt_dt(iso: str | None) -> str:
    if not iso:
        return "—"
    try:
        dt = datetime.fromisoformat(iso)
        diff = datetime.now(timezone.utc) - dt
        secs = int(diff.total_seconds())
        if secs < 60:
            return f"{secs}s ago"
        if secs < 3600:
            return f"{secs // 60}m ago"
        if secs < 86400:
            return f"{secs // 3600}h ago"
        return f"{secs // 86400}d ago"
    except Exception:
        return iso[:16]


def _fmt_dur(dur: float | None) -> str:
    if dur is None:
        return ""
    if dur < 1:
        return f"{int(dur * 1000)}ms"
    return f"{dur:.1f}s"


def _fmt_tok(n: int) -> str:
    if n >= 1_000_000:
        return f"{n/1_000_000:.1f}M"
    if n >= 1_000:
        return f"{n/1_000:.1f}K"
    return str(n)


def _fmt_window_reset(seconds: float) -> str:
    minutes = max(1, int((seconds + 59) // 60))
    hours, mins = divmod(minutes, 60)
    if hours >= 24:
        days, rem_hours = divmod(hours, 24)
        return f"{days}d{rem_hours:02d}h"
    if hours > 0:
        return f"{hours}h{mins:02d}m"
    return f"{minutes}m"


def _normalize_window_reset(d: dict, now: datetime | None = None) -> dict:
    """Keep a reset timestamp inside its declared rolling window."""
    out = dict(d)
    try:
        resets_at = float(out.get("resets_at_unix") or 0)
        window_minutes = float(out.get("window_minutes") or 0)
    except (TypeError, ValueError):
        return out
    if resets_at <= 0 or window_minutes <= 0:
        return out

    now_dt = now or datetime.now(timezone.utc)
    now_unix = now_dt.timestamp()
    window_seconds = window_minutes * 60
    remaining = resets_at - now_unix
    if remaining > window_seconds:
        remaining = remaining % window_seconds
        if remaining <= 0:
            remaining = window_seconds
        out["resets_at_unix"] = int(now_unix + remaining)
        out["reset"] = _fmt_window_reset(remaining)
    return out


def _normalize_windows(w: dict) -> dict:
    now = datetime.now(timezone.utc)
    out = dict(w)
    for key in ("window_5h", "window_7d"):
        if isinstance(out.get(key), dict):
            out[key] = _normalize_window_reset(out[key], now)
    return out


def _parse_run_started_at(raw: str | None) -> datetime | None:
    if not raw:
        return None
    try:
        dt = datetime.fromisoformat(str(raw).replace("Z", "+00:00"))
    except (TypeError, ValueError):
        return None
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.astimezone(timezone.utc)


def _observed_run_window_usage(agent: str, minutes: int, now: datetime | None = None) -> dict:
    """Count observed local run tokens when quota APIs omit a current window."""
    now_dt = now or datetime.now(timezone.utc)
    cutoff = now_dt - timedelta(minutes=minutes)
    latest_by_run_id: dict[str, dict] = {}
    for path in (RUN_LOG, PROTO_RUN_LOG, STATE_RUN_LOG):
        if not path.exists():
            continue
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        for idx, line in enumerate(lines):
            try:
                record = json.loads(line)
            except Exception:
                continue
            if (record.get("agent") or "claude") != agent:
                continue
            started = _parse_run_started_at(record.get("started_at"))
            if not started or started < cutoff or started > now_dt:
                continue
            tokens = int(record.get("input_tokens") or 0) + int(record.get("output_tokens") or 0)
            if tokens <= 0:
                continue
            run_id = str(record.get("run_id") or f"{path}:{idx}")
            prior = latest_by_run_id.get(run_id)
            prior_started = _parse_run_started_at(prior.get("started_at")) if prior else None
            if prior is None or (prior_started and started >= prior_started):
                latest_by_run_id[run_id] = record
    tokens = sum(int(r.get("input_tokens") or 0) + int(r.get("output_tokens") or 0)
                 for r in latest_by_run_id.values())
    return {"tokens": tokens, "sessions": len(latest_by_run_id)}


