# Auto-rebuild registry if stale (any skill.yaml newer than registry.json)
def _maybe_rebuild_registry() -> None:
    _build_script = KNOWLEDGE_BASE_ROOT / ".codex" / "skills" / "skill-registry" / "scripts" / "build_registry.py"
