def _pipe_fd(pipe) -> int | None:
    try:
        return pipe.fileno()
    except (AttributeError, OSError, ValueError):  # io.UnsupportedOperation is both
        return None


def _iter_pipe_chunks(pipe, stop: threading.Event):
    """Raw chunks until EOF or `stop`. Polls `stop` every 0.25 s, so a descendant that escaped
    the group and still holds the pipe cannot pin the reader past a timeout (BUILD-014).
    A double without a descriptor yields its read() once (WS-008)."""
    fd = _pipe_fd(pipe)
    if fd is None:
        data = pipe.read()
        if data:
            yield data
        return
    # selectors, not select(): no FD_SETSIZE ceiling on busy hosts with many open files (RWS-019)
    with selectors.DefaultSelector() as sel:
        sel.register(fd, selectors.EVENT_READ)
        while not stop.is_set():
            if not sel.select(0.25):
                continue
            chunk = os.read(fd, 65536)
            if not chunk:
                return
            yield chunk


def _iter_pipe_lines(pipe, stop: threading.Event):
    """Lines (with their newline) until EOF or `stop`; the buffered pipe object is never read.
    A double without a descriptor is iterated (WS-008)."""
    if _pipe_fd(pipe) is None:
        yield from pipe
        return
    buf = b""
    for chunk in _iter_pipe_chunks(pipe, stop):
        buf += chunk
        *lines, buf = buf.split(b"\n")
        for line in lines:
            if stop.is_set():  # a big buffered chunk never outlives the stop (RWS-009)
                return
            yield line + b"\n"
    if buf and not stop.is_set():
        yield buf


def _guarded(fn, errors: list):
    """A reader whose exception is kept for its controller instead of dying silently in the
    thread; the controller then cleans up and re-raises it (RWS-019)."""
    @functools.wraps(fn)
    def run():
        try:
            fn()
        except BaseException as exc:
            errors.append(exc)
    return run


def _timeout_cleanup(proc, stop: threading.Event, readers: list[threading.Thread]) -> None:
    """Every streamed-run timeout: stop the readers, kill the whole group, reap, and give the
    readers a moment to end so their in-flight slots return (BUILD-014, WS-001)."""
    stop.set()
    _kill_and_reap(proc)
    for r in readers:
        r.join(timeout=2)


STDERR_LIVE_LINES = 200


class _StderrSink:
    """stderr lines as they arrive: shown live in the run view (bounded) and their tail kept for
    replay on every exit, a timeout included (UI8-03)."""

    def __init__(self, run_id: str | None):
        self.run_id, self.buf, self.shown = run_id, b"", 0
        self.tail: collections.deque = collections.deque(maxlen=STDERR_TAIL_LINES)

    def feed(self, chunk: bytes) -> None:
        job = _running_jobs.get(self.run_id) if self.run_id and chunk else None
        if job is not None:
            job["last_progress_at"] = time.monotonic()  # any stderr byte is progress, newline or whitespace (UI27-01, DS-01)
        self.buf += chunk
        *lines, self.buf = self.buf.split(b"\n")
        for raw in lines:
            self._line(raw.decode("utf-8", errors="replace"))

    def _line(self, ln: str) -> None:
        if not ln.strip():
            return
        ln = ln[:300]
        if not self.run_id:
            self.tail.append({"pos": 0, "line": ln})
            return
        # Position and live publication together under the run's order lock, the same lock a
        # stdout line holds from its log write to its publication: live and replay agree (FINAL-02, UI27-02).
        with project_runs.order_lock(self.run_id):
            try:
                pos = _claude_stream_log_path(self.run_id).stat().st_size
            except OSError:
                pos = 0
            self.tail.append({"pos": pos, "line": ln})
            if self.shown < STDERR_LIVE_LINES:
                self.shown += 1
                shown = f"\x1b[31m[stderr] {ln}\x1b[0m"
                socketio.emit("run_event", {"run_id": self.run_id, "line": shown,
                                            "seq": project_runs.ring_for(self.run_id).append(shown)})

    def close(self) -> None:
        if self.buf:
            self._line(self.buf.decode("utf-8", errors="replace"))
            self.buf = b""
        if self.run_id and self.tail:
            with contextlib.suppress(OSError):
                meta_path = _stream_meta_path(self.run_id)
                meta = read_json(meta_path) or {}
                meta["stderr_tail"] = ((meta.get("stderr_tail") or []) + list(self.tail))[-STDERR_TAIL_LINES * 2:]
                write_json_atomic(meta_path, meta)


def _read_both(proc, stdout_reader, stop: threading.Event, timeout: float, run_id: str | None = None) -> str:
    """Run the stdout reader and a stderr drain side by side under one deadline (WS-001), so a
    chatty stderr can never block the child before it closes stdout (UI-04). Any failure or
    timeout stops both, kills and reaps the group (RWS-004/019). Returns the stderr text."""
    stderr_chunks: list[bytes] = []
    sink = _StderrSink(run_id)

    def _drain_stderr() -> None:
        if proc.stderr is not None:
            for chunk in _iter_pipe_chunks(proc.stderr, stop):
                stderr_chunks.append(chunk)
                sink.feed(chunk)

    deadline = time.monotonic() + timeout
    readers: list[threading.Thread] = []
    errors: list[BaseException] = []
    try:
        for fn in (stdout_reader, _drain_stderr):  # counted until they stop writing, even past a timeout (BUILD-014)
            readers.append(_start_counted(_guarded(fn, errors), _thread=_REAL_THREAD))
        while not errors and any(r.is_alive() for r in readers) and time.monotonic() < deadline:
            for r in readers:
                r.join(timeout=min(0.25, max(0.0, deadline - time.monotonic())))
        if errors:  # a reader failed: same cleanup, then the error reaches the worker (RWS-019)
            raise errors[0]
        if any(r.is_alive() for r in readers):
            raise subprocess.TimeoutExpired(proc.args, timeout)
        proc.wait(timeout=max(0.0, deadline - time.monotonic()))
    except subprocess.TimeoutExpired:
        _timeout_cleanup(proc, stop, readers)
        raise subprocess.TimeoutExpired(proc.args, timeout)
    except BaseException:  # a reader could not start: never leave the child running (RWS-004)
        _timeout_cleanup(proc, stop, readers)
        raise
    finally:
        sink.close()  # the tail is kept for replay on every exit, a timeout included
    return b"".join(stderr_chunks).decode("utf-8", errors="replace").strip()


